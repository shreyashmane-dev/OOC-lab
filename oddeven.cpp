
#include<iostream>
using namespace std;


int main()
{
int n;

cout<<"Enter the number to check even or odd: "<<endl;
cin>>n;

if(n%2==0)
{
  cout<<"The number "<<n<<" is even"<<endl;
}

else
{
  cout<<"The number "<<n<<" is odd"<<endl;
}
cout<<"End of the program"<<endl;
return 0;
}




























































































